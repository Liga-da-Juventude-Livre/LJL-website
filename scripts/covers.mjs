// Book covers live in assets/books/covers/<slug>.jpg and are imported through assets/books/covers/index.ts.
//
//   node scripts/covers.mjs add <slug> <image-file> [--trim]   normalise one cover (JPEG, at most 900px wide) and refresh the index;
//                                                              --trim cuts uniform white margins around the artwork
//   node scripts/covers.mjs index                      only regenerate index.ts from the files present
//
// <slug> is the book's address in the library (for example "as-seis-licoes"). A book without a cover file falls back to
// a typeset cover automatically, so adding covers one at a time is fine.
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "assets", "books", "covers");
const MAX_WIDTH = 900;

async function add(slug, input, trim) {
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug)) throw new Error(`Slug inválido: ${slug}`);
  const out = path.join(dir, `${slug}.jpg`);
  let image = sharp(input).rotate().flatten({ background: "#ffffff" });
  if (trim) image = sharp(await image.toBuffer()).trim({ background: "#ffffff", threshold: 14 });
  const info = await image
    .resize({ width: MAX_WIDTH, withoutEnlargement: true })
    .jpeg({ quality: 86, mozjpeg: true })
    .toFile(out);
  console.log(`${slug}.jpg  ${info.width}x${info.height}  ${(info.size / 1024).toFixed(0)} KB`);
}

async function index() {
  const files = (await fs.readdir(dir)).filter((f) => /\.jpe?g$/i.test(f)).sort();
  const name = (f) => `cover_${f.replace(/\.[^.]+$/, "").replace(/-/g, "_")}`;
  const body = [
    "// Generated by scripts/covers.mjs. Do not edit by hand: add a cover with `node scripts/covers.mjs add <slug> <file>`.",
    'import type { StaticImageData } from "next/image";',
    "",
    ...files.map((f) => `import ${name(f)} from "./${f}";`),
    "",
    "/** Real book covers by library slug. Books missing here use a typeset cover. See CREDITS.md for where each came from. */",
    "export const bookCovers: Record<string, StaticImageData> = {",
    ...files.map((f) => `  "${f.replace(/\.[^.]+$/, "")}": ${name(f)},`),
    "};",
    "",
  ].join("\n");
  await fs.writeFile(path.join(dir, "index.ts"), body);
  console.log(`index.ts: ${files.length} covers`);
}

const [cmd, ...args] = process.argv.slice(2);
if (cmd === "add" && args.filter((a) => a !== "--trim").length === 2) {
  await add(args[0], args[1], args.includes("--trim"));
  await index();
} else if (cmd === "index") {
  await index();
} else {
  console.error("Uso: node scripts/covers.mjs add <slug> <arquivo>  |  node scripts/covers.mjs index");
  process.exit(1);
}
